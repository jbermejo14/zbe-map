function generateCityPolygon(lat: number, lng: number, radiusKm = 0.8): [number, number][] {
  const points: [number, number][] = [];
  const numSides = 8;
  const latDelta = radiusKm / 111;
  const lngDelta = radiusKm / (111 * Math.cos((lat * Math.PI) / 180));

  for (let i = 0; i < numSides; i++) {
    const angle = (i * 2 * Math.PI) / numSides;
    const pLat = Number((lat + latDelta * Math.sin(angle)).toFixed(6));
    const pLng = Number((lng + lngDelta * Math.cos(angle)).toFixed(6));
    points.push([pLat, pLng]);
  }
  points.push(points[0]); // cerrar
  return points;
}

function run() {
  const citiesPath = path.join(__dirname, '../data/zbe-cities.json');
  const existingCities: any[] = JSON.parse(fs.readFileSync(citiesPath, 'utf8'));

  const existingIds = new Set(existingCities.map((c) => c.id));
  let added = 0;

  for (const c of newCities) {
    if (existingIds.has(c.id)) {
      continue;
    }

    const cityEntry = {
      id: c.id,
      slug: c.slug,
      name: c.name,
      province: c.province,
      region: c.region,
      lat: c.lat,
      lng: c.lng,
      status: c.status,
      fineAmount: c.fineAmount,
      schedule: c.schedule,
      summary: c.summary,
      parkingCondition: c.parkingCondition || 'Libre circulación para residentes y servicios; vehículos con etiqueta sujetos a aparcamiento.',
      exemptions: c.exemptions,
      rules: {
        SIN_ETIQUETA: {
          status: 'banned',
          reason: `Prohibido el acceso y circulación en la ZBE de ${c.name}. Sanción oficial de ${c.fineAmount} € captada mediante cámaras OCR.`
        },
        B: {
          status: 'restricted',
          reason: `Acceso restringido en horario regulado (${c.schedule}). Permite acceso para estacionar en parkings subterráneos adheridos.`
        },
        C: {
          status: 'allowed',
          reason: `Circulación permitida sin restricciones de horario en la ZBE de ${c.name}.`
        },
        ECO: {
          status: 'allowed',
          reason: `Acceso y circulación 100% libre sin restricciones. Bonificación en estacionamiento regulado.`
        },
        CERO: {
          status: 'allowed',
          reason: `Acceso prioritario y circulación totalmente libre. Estacionamiento gratuito e ilimitado.`
        }
      },
      perimeterName: c.perimeterName,
      areaKm2: c.areaKm2,
      polygon: generateCityPolygon(c.lat, c.lng, Math.sqrt(c.areaKm2 / Math.PI))
    };

    existingCities.push(cityEntry);
    added++;
  }

  fs.writeFileSync(citiesPath, JSON.stringify(existingCities, null, 2), 'utf8');
  console.log(`✅ Añadidas ${added} nuevas ciudades. Total actual: ${existingCities.length} ciudades ZBE.`);
}

run();
